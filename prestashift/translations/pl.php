        foreach ($phraseMap[$phrase] as $ctx) {
            $md5 = md5($phrase);
            $_MODULE['<{prestashift}prestashop>' . $ctx . '_' . $md5] = $trans;
        }
    } else {
        // Fallback for any key not found in map (defaults to controller)
        $md5 = md5($phrase);
        $_MODULE['<{prestashift}prestashop>adminprestashiftmigrationcontroller_' . $md5] = $trans;
    }
}

