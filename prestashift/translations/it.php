foreach ($translations as $phrase => $trans) {
    if (empty($trans)) {
        continue;
    }
    if (isset($phraseMap[$phrase])) {
        foreach ($phraseMap[$phrase] as $ctx) {
            $_MODULE['<{prestashift}prestashop>' . $ctx . '_' . md5($phrase)] = $trans;
        }
    } else {
        $_MODULE['<{prestashift}prestashop>adminprestashiftmigrationcontroller_' . md5($phrase)] = $trans;
    }
}
